package cc.starsector.client;

/**
 * The engine-name dictionary for the mod's reflective seams: the one place a by-name lookup into the
 * engine's internal classes asks "what is this class / member called on the engine build I am running on?".
 *
 * <p>WHY: the Linux download of the game is a separate build of the engine — 18 internal classes and 11 members
 * the mod names carry a different name there. Compiled references are renamed at class load by the
 * compat agent; the by-NAME lookups ({@code Class.forName}, {@code MethodHandles.Lookup.find*} with a string)
 * cannot be, so each wraps its Windows spelling in {@link #cls} / {@link #member}. Both return the input until
 * the link probe latches the agent's receipt at application load: on Windows, on a Linux box
 * running the Windows jars, and with no agent, the dictionary is the identity.
 *
 * <p>The bodies. The table is {@link EngineNameTable}, generated by the client
 * build from the checked-in engine map; the receipt is the agent's {@code cc.engine.map} system property, read ONCE
 * by {@link EngineLinkProbe#verifyAtApplicationLoad} and latched here — never a per-call property read, so a later
 * agent write can never flip a seam's spelling mid-combat. The translation applies iff the latched receipt equals
 * {@link EngineNameTable#MAP_ID}. Lookups are exact, case-sensitive {@code String.equals} scans (18 + 11 rows: no
 * collection, no allocation). The descriptor on {@link #member} is required because the mapped owners carry
 * overloads of the same name.
 */
public final class EngineNames {
    private EngineNames() {}

    /** The receipt latched when the agent set none (a start without the kit's launcher, or a build-time run). */
    static final String UNSET = "unset";

    /** The latched receipt; {@code null} until {@link #latch} runs. Written once. */
    private static volatile String latchedReceipt;

    /** True iff the latched receipt names this build's generated map; false before the latch (= identity). */
    private static volatile boolean mapped;

    /**
     * Latch the agent's receipt ONCE (the first call wins; a later call is ignored and returns false). A
     * {@code null} receipt latches {@link #UNSET}, which never maps.
     */
    static synchronized boolean latch(String receipt) {
        if (latchedReceipt != null) {
            return false;
        }
        String r = receipt == null ? UNSET : receipt;
        mapped = EngineNameTable.MAP_ID.equals(r);
        latchedReceipt = r;
        return true;
    }

    /** The latched receipt, {@link #UNSET} before the latch or when the agent set none. */
    static String receipt() {
        String r = latchedReceipt;
        return r == null ? UNSET : r;
    }

    /** Whether the latched receipt selects the generated map (false before the latch). */
    static boolean mapped() {
        return mapped;
    }

    /** The engine class's dotted name on this build; identity until the probe latches a map. */
    public static String cls(String winDotted) {
        return clsFor(winDotted, mapped);
    }

    /**
     * The engine member's name on this build, keyed by its Windows owner (dotted), name and descriptor; identity
     * until the probe latches a map. A descriptor-renamed parameter class goes through {@link #cls} separately.
     */
    public static String member(String winOwnerDotted, String name, String winDesc) {
        return memberFor(winOwnerDotted, name, winDesc, mapped);
    }

    /** {@link #cls} with the map choice explicit: the probe's build-time control runs the other spelling. */
    static String clsFor(String winDotted, boolean map) {
        if (!map) {
            return winDotted;
        }
        String[] t = EngineNameTable.CLASSES;
        for (int i = 0; i < t.length; i += EngineNameTable.CLASS_STRIDE) {
            if (t[i].equals(winDotted)) {
                return t[i + 1];
            }
        }
        return winDotted;
    }

    /** {@link #member} with the map choice explicit. */
    static String memberFor(String winOwnerDotted, String name, String winDesc, boolean map) {
        int row = map ? memberRow(winOwnerDotted, name, winDesc) : -1;
        return row < 0 ? name : EngineNameTable.MEMBERS[row + EngineNameTable.M_LINUX_NAME];
    }

    /**
     * The member's descriptor on this build (internal form, the class rows applied) — what a probe hands
     * {@code MethodType.fromMethodDescriptorString}; the Windows descriptor when unmapped or not a member row.
     */
    static String descFor(String winOwnerDotted, String name, String winDesc, boolean map) {
        int row = map ? memberRow(winOwnerDotted, name, winDesc) : -1;
        return row < 0 ? winDesc : EngineNameTable.MEMBERS[row + EngineNameTable.M_LINUX_DESC];
    }

    /** The MEMBERS offset of the exact (owner, name, descriptor) row, or -1. */
    private static int memberRow(String winOwnerDotted, String name, String winDesc) {
        String[] m = EngineNameTable.MEMBERS;
        for (int i = 0; i < m.length; i += EngineNameTable.MEMBER_STRIDE) {
            if (m[i + EngineNameTable.M_OWNER].equals(winOwnerDotted) && m[i + EngineNameTable.M_NAME].equals(name)
                    && m[i + EngineNameTable.M_WIN_DESC].equals(winDesc)) {
                return i;
            }
        }
        return -1;
    }
}
